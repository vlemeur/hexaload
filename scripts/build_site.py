"""Generate the site's JSON data from ``results/`` (never hand-edit).

Writes ``docs/data/results.json`` — fetched client-side by the pages (raw
githubusercontent) so a push of this file updates the site without a rebuild.
Run via ``just site`` before ``zensical build``.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"
TUNING = RESULTS / "tuning"
DOCS = ROOT / "docs"
DATA = DOCS / "data"

GENERATED = "<!-- GENERATED by scripts/build_site.py — do not edit. -->\n\n"

logger = logging.getLogger(__name__)


def md_table(df: pd.DataFrame, cols: list[tuple[str, str, str]]) -> str:
    """Markdown table; cols = (df column, header, format)."""
    head = "| " + " | ".join(h for _, h, _ in cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    lines = [head, sep]
    for _, row in df.iterrows():
        cells = []
        for c, _, fmt in cols:
            v = row[c]
            cells.append(fmt.format(v) if fmt else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def load_parquet(path: Path) -> pd.DataFrame | None:
    if not path.exists():
        logger.warning("missing %s — page will say the run is pending", path)
        return None
    return pd.read_parquet(path)


def study_stats() -> dict[str, dict]:
    """Per-study trial counts + Pareto size from the Optuna SQLite storage."""
    import optuna

    db = ROOT / "data/tuning/optuna.db"
    if not db.exists():
        return {}
    out: dict[str, dict] = {}
    storage = f"sqlite:///{db}"
    for s in optuna.get_all_study_summaries(storage=storage):
        st = optuna.load_study(study_name=s.study_name, storage=storage)
        comp = [t for t in st.trials if t.state == optuna.trial.TrialState.COMPLETE]
        best = min(comp, key=lambda t: t.values[0]) if comp else None
        out[s.study_name.removeprefix("hexaload-")] = {
            "trials": len(st.trials),
            "complete": len(comp),
            "pareto": len(st.best_trials),
            "best_mase": round(best.values[0], 4) if best else None,
            "best_crps": round(best.values[1], 1) if best else None,
        }
    return out


def main() -> int:
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(message)s")
    DOCS.mkdir(exist_ok=True)
    DATA.mkdir(exist_ok=True)

    tuned = load_parquet(RESULTS / "backtest_tuned.parquet")
    default = load_parquet(RESULTS / "backtest_default.parquet")
    posthoc = load_parquet(RESULTS / "backtest_posthoc.parquet")
    if tuned is not None and posthoc is not None:
        # wrapper rows join the main 36-fold table; the fresh tuned parquet wins
        tuned = pd.concat([tuned, posthoc]).drop_duplicates(
            subset=["model"], keep="first"
        )
    # slow TSFM rows are kept in a side parquet (recomputed only on full benches)
    tsfm = load_parquet(RESULTS / "backtest_tsfm.parquet")
    if tuned is not None and tsfm is not None:
        have = set(tuned["model"])
        tuned = pd.concat([tuned, tsfm[~tsfm["model"].isin(have)]])
    holdout = load_parquet(TUNING / "holdout.parquet")
    params_path = TUNING / "best_params.yaml"
    yaml.safe_load(params_path.read_text()) if params_path.exists() else {}

    stats = study_stats()

    data_json = {
        "backtest_tuned": tuned.to_dict(orient="records")
        if tuned is not None
        else None,
        "backtest_default": default.to_dict(orient="records")
        if default is not None
        else None,
        "holdout": holdout.to_dict(orient="records") if holdout is not None else None,
        "tuning": stats,
    }
    results_path = DATA / "results.json"
    if tuned is None and default is None and holdout is None and results_path.exists():
        # CI checkout has no results/ (gitignored): keep the committed results.json
        logger.info("no results/ in checkout — keeping committed %s", results_path)
    else:
        results_path.write_text(json.dumps(data_json, indent=1, default=str))
    for stale in ("results.md", "benchmark.md", "holdout.md", "tuning.md"):
        p = DOCS / stale
        if p.exists():
            p.unlink()
    logger.info("site data written to %s", DOCS)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
